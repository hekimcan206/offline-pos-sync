using PosSync.Core.Model;
using PosSync.UnitTests.Merge;
using PosSync.UnitTests.Support;

namespace PosSync.UnitTests.Conflicts;

public sealed class ConflictScenarioTests
{
    public static TheoryData<string> Ids => [.. ConflictScenarios.All.Select(s => s.Id)];

    [Theory]
    [MemberData(nameof(Ids))]
    public void Scenario_produces_the_documented_outcome(string id)
    {
        var scenario = ConflictScenarios.All.Single(s => s.Id == id);
        var outcomes = new List<string>();
        foreach (var reverse in new[] { false, true })
        {
            var world = new ScenarioWorld(ConvergencePropertyTests.SchemaFor(scenario.Strategy), reverse);

            scenario.Run(world);

            var replicaHashes = world.Replicas.Select(r => r.Hash()).Distinct().ToList();
            replicaHashes.Should().ContainSingle($"all replicas must converge ({(reverse ? "reverse" : "in-order")} delivery)");
            outcomes.Add(Values(world.Server));
        }

        // Stamps may differ between the two runs (an HLC counter depends on the order in which a terminal observed
        // remote timestamps), so the cross-run comparison is on values: what a cashier or report would see.
        outcomes[0].Should().Be(outcomes[1], "the outcome must not depend on delivery order");
    }

    private static string Values(Core.Merge.InMemoryReplica replica) =>
        string.Join('\n', replica.States
            .OrderBy(s => s.Entity, StringComparer.Ordinal).ThenBy(s => s.EntityId)
            .Select(s => $"{s.Entity}/{s.EntityId}: " +
                string.Join(';', s.Registers.Select(r => $"{r.Key}={r.Value.Value}")) + " | " +
                string.Join(';', s.Counters.Select(c => $"{c.Key}={c.Value}"))));

    [Fact]
    public void Catalogue_covers_every_strategy_and_has_unique_ids()
    {
        ConflictScenarios.All.Select(s => s.Id).Should().OnlyHaveUniqueItems();
        ConflictScenarios.All.Select(s => s.Strategy).Distinct().Should()
            .BeEquivalentTo([MergeStrategy.RowLww, MergeStrategy.FieldLww, MergeStrategy.DomainRules]);
    }

    [Fact]
    public void Documented_table_matches_the_catalogue()
    {
        var path = Path.Combine(RepoPaths.Root, "docs", "conflict-scenarios.md");
        var expected = ConflictScenarios.RenderMarkdown();
        if (Environment.GetEnvironmentVariable("UPDATE_GOLDEN") == "1")
        {
            File.WriteAllText(path, expected);
        }

        File.Exists(path).Should().BeTrue("docs/conflict-scenarios.md is generated by this test with UPDATE_GOLDEN=1");
        File.ReadAllText(path).ReplaceLineEndings("\n").Should().Be(expected.ReplaceLineEndings("\n"));
    }
}
